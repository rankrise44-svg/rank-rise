export function generateInitialCandles(basePrice: number, count: number = 70, timeframeMinutes: number = 5): Candle[] {
  const candles: Candle[] = [];
  const now = Date.now();
  const stepMs = timeframeMinutes * 60 * 1000;
  let currentClose = basePrice;
  const volatility = basePrice * 0.0012;

  for (let i = count; i >= 0; i--) {
    const time = now - (i * stepMs);
    const delta = (Math.random() - 0.49) * volatility;
    const open = currentClose;
    const close = +(open + delta).toFixed(5);
    const highDelta = Math.random() * volatility * 0.8;
    const lowDelta = Math.random() * volatility * 0.8;
    const high = +(Math.max(open, close) + highDelta).toFixed(5);
    const low = +(Math.min(open, close) - lowDelta).toFixed(5);
    const volume = Math.floor(200 + Math.random() * 800);

    candles.push({
      time,
      open,
      high,
      low,
      close,
      volume
    });
    currentClose = close;
  }
  return candles;
}

